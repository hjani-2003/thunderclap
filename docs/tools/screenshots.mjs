// Captures the web-UI screenshots used in the user guide, plus a small CSS
// file that positions the numbered markers on the annotated overview.
// Needs a running daemon, ideally with an active transfer:
//   node docs/tools/screenshots.mjs http://127.0.0.1:8080/#token=…  docs/img  [folder to show]
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { launch } from './cdp.mjs';

const [url, outDir = 'docs/img', startPath] = process.argv.slice(2);
if (!url) {
  console.error('usage: screenshots.mjs <ui-url-with-token> [outdir] [folder to show]');
  process.exit(2);
}

const W = 1360, H = 960;
const b = await launch();
const save = (name, buf) => { writeFileSync(join(outDir, name), buf); console.log('wrote', name); };

// Bounding box of a dialog, padded, for a tight crop.
async function dialogClip(id, pad = 0) {
  const r = await b.eval(`(() => { const r = document.getElementById('${id}').getBoundingClientRect();
    return { x: r.x, y: r.y, width: r.width, height: r.height }; })()`);
  return { x: r.x - pad, y: r.y - pad, width: r.width + 2 * pad, height: r.height + 2 * pad };
}

await b.colorScheme('light');
await b.viewport(W, H);
await b.goto(url, 9000);          // let the throughput chart collect some history
if (startPath) {
  // Show a demo folder instead of the real home directory, with one item selected.
  await b.eval(`(() => { const p = document.getElementById('path'); p.value = ${JSON.stringify(startPath)};
    p.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' })); })()`);
  await b.sleep(800);
  await b.eval(`document.querySelector('#files .frow')?.click()`);
  await b.sleep(300);
}

// Marker positions: just right of a heading's text, or just left of a control.
const pins = await b.eval(`(() => {
  const textRect = (el) => { const r = document.createRange(); r.selectNodeContents(el); return r.getBoundingClientRect(); };
  const firstText = (el) => { const r = document.createRange(); r.selectNode(el.firstChild); return r.getBoundingClientRect(); };
  const heading = (t) => [...document.querySelectorAll('h2')].find((h) => h.textContent.trim() === t);
  const label = (t) => [...document.querySelectorAll('label')].find((l) => l.firstChild?.textContent.trim() === t);
  const right = (r) => ({ x: r.right + 28, y: r.top + r.height / 2 });
  const left = (r) => ({ x: r.left - 28, y: r.top + r.height / 2 });
  return [
    right(document.getElementById('dev-cipher').getBoundingClientRect()),
    left(document.getElementById('btn-recv-code').getBoundingClientRect()),
    right(textRect(heading('Peers'))),
    right(textRect(heading('Send'))),
    right(firstText(label('Streams'))),
    left(document.getElementById('btn-bench').getBoundingClientRect()),
    right(textRect(heading('Throughput'))),
    right(textRect(heading('Transfers'))),
    left(document.querySelector('.xfer .state').getBoundingClientRect()),
  ];
})()`);
save('ui-overview.png', await b.screenshot());
const css = pins.map((p, i) =>
  `.annotated .pin.p${i + 1} { left: ${(100 * p.x / W).toFixed(2)}%; top: ${(100 * p.y / H).toFixed(2)}%; }`).join('\n');
save('ui-overview-pins.css', Buffer.from('/* generated by docs/tools/screenshots.mjs */\n' + css + '\n'));

// Dialogs are cropped tightly, so hide the dimmed backdrop behind their rounded corners.
await b.eval(`document.head.insertAdjacentHTML('beforeend',
  '<style>dialog::backdrop{background:transparent!important;backdrop-filter:none!important}dialog{box-shadow:none!important}</style>')`);

// Pairing dialog (cropped)
await b.eval(`document.getElementById('btn-pair-code').click()`);
await b.sleep(1200);
save('ui-pair.png', await b.screenshot(await dialogClip('dlg-code')));
await b.eval(`document.querySelector('#dlg-code [data-close]').click()`);

// Settings dialog (cropped)
await b.eval(`document.getElementById('btn-settings').click()`);
await b.sleep(600);
save('ui-settings.png', await b.screenshot(await dialogClip('dlg-settings')));
await b.eval(`document.querySelector('#dlg-settings [data-close]').click()`);

// Dark theme
await b.colorScheme('dark');
await b.sleep(1500);
save('ui-dark.png', await b.screenshot());

// Phone width
await b.colorScheme('light');
await b.viewport(390, 844, 2, true);
await b.sleep(1500);
const overflow = await b.eval('document.documentElement.scrollWidth - window.innerWidth');
if (overflow > 0) console.warn(`warning: page is ${overflow}px wider than a phone screen`);
save('ui-mobile.png', await b.screenshot());

await b.close();
