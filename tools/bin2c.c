/* Build-time helper: turns files into C arrays so the web UI can be
 * compiled into the binary on any C compiler (no #embed needed).
 *
 *   bin2c NAME FILE [NAME FILE]...  > out.c
 *
 * For each pair it emits `const char NAME[]` (NUL-terminated) and
 * `const size_t NAME_len` (length without the NUL). */
#include <stdio.h>

int main(int argc, char **argv)
{
    if (argc < 3 || argc % 2 == 0) {
        fprintf(stderr, "usage: bin2c NAME FILE [NAME FILE]...\n");
        return 2;
    }
    printf("/* generated by tools/bin2c.c — do not edit */\n#include <stddef.h>\n\n");
    for (int i = 1; i < argc; i += 2) {
        FILE *f = fopen(argv[i + 1], "rb");
        if (!f) {
            perror(argv[i + 1]);
            return 1;
        }
        printf("const char %s[] = {", argv[i]);
        size_t n = 0;
        int c;
        while ((c = fgetc(f)) != EOF) {
            printf("%s%d,", n % 24 ? "" : "\n    ", c);
            n++;
        }
        fclose(f);
        printf("\n    0\n};\nconst size_t %s_len = %zu;\n\n", argv[i], n);
    }
    return 0;
}
